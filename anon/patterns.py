# -*- coding: utf-8 -*-
"""Что считать секретом.

Порядок правил важен: сначала длинные и конкретные образцы, потом общие.
Иначе токен внутри ссылки будет разобран по частям и превратится в мусор,
из которого уже ничего не восстановить.
"""
import re

# Каждое правило — (вид, выражение). Вид становится префиксом метки:
# KEY_1, MAIL_2 и так далее.
PATTERNS = [
    # ── ключи и токены ──────────────────────────────────────────────
    ("TOKEN", re.compile(r"\b\d{8,10}:[A-Za-z0-9_-]{30,}\b")),          # Telegram
    ("KEY", re.compile(r"(?i)\b(?:sk|pk|api|key|token|secret)[-_][A-Za-z0-9_-]{16,}\b")),
    ("BEARER", re.compile(r"(?i)(?<=Bearer )[A-Za-z0-9._-]{20,}")),
    ("BASIC", re.compile(r"(?i)(?<=Basic )[A-Za-z0-9+/=]{16,}")),

    # Присваивание вида api_key = "...". Просмотр назад тут не годится:
    # Python требует для него фиксированной длины, а префикс переменный.
    # Поэтому ловим выражение целиком, а заменяем только вторую группу.
    ("SECRET", re.compile(
        r"(?i)((?:password|passwd|pwd|secret|api_key|apikey|token|access_key)"
        r"[\"']?\s*[:=]\s*[\"'])([^\"'\n]{6,})")),

    # ── контакты ────────────────────────────────────────────────────
    ("MAIL", re.compile(r"\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}\b")),
    ("PHONE", re.compile(
        r"(?<![\d.])(?:\+7|8)[\s(-]?\d{3}[\s)-]?\d{3}[\s-]?\d{2}[\s-]?\d{2}(?![\d.])")),
    ("INN", re.compile(r"(?<!\d)\d{10}(?!\d)|(?<!\d)\d{12}(?!\d)")),

    # ── сеть ────────────────────────────────────────────────────────
    ("IP", re.compile(r"(?<![\d.])(?:\d{1,3}\.){3}\d{1,3}(?![\d.])")),
    ("HOST", re.compile(r"\b(?:[a-z0-9-]+\.)+(?:ru|com|net|org|io|dev|pro|рф)\b", re.I)),

    # ── пути с именем пользователя ──────────────────────────────────
    # Слэшей может быть несколько: в логах Windows путь часто приезжает
    # экранированным — C:\\Users\\ivan. Просмотр назад тут не работает,
    # он требует фиксированной длины, поэтому ловим с группой.
    ("USER", re.compile(r"([Uu]sers[\\/]+)([^\\/\s\"']{2,})")),
    ("HOME", re.compile(r"(/home/+)([^/\s\"']{2,})")),
]

# Правила, где значение лежит во второй группе, а первую надо сохранить:
# имя поля, «Users\» и кавычка должны остаться на месте, иначе строка
# развалится и лог перестанет читаться.
GROUPED = {"SECRET", "USER", "HOME"}

# Что не трогаем. Служебные адреса и общеизвестные домены секретами не
# являются, а без них обезличенный лог становится нечитаемым: непонятно,
# куда вообще ходила программа.
KEEP = {
    "127.0.0.1", "0.0.0.0", "255.255.255.255", "8.8.8.8", "1.1.1.1",
    "localhost", "example.com", "python.org", "github.com",
    "api.telegram.org", "docker.io",
}

# Тексты для отчёта: человеку понятнее «почта», чем MAIL.
TITLES = {
    "TOKEN": "токены Telegram",
    "KEY": "ключи API",
    "BEARER": "заголовки Bearer",
    "BASIC": "заголовки Basic",
    "SECRET": "пароли и ключи в коде",
    "MAIL": "почта",
    "PHONE": "телефоны",
    "INN": "ИНН",
    "IP": "адреса серверов",
    "HOST": "домены",
    "USER": "имена пользователей в путях",
    "HOME": "домашние каталоги",
    "NAME": "свои слова из words.txt",
}
